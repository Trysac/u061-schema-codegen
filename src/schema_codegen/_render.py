"""Render the model graph to Pydantic v2 and TypeScript source text."""

from __future__ import annotations

import json
import re
from collections.abc import Iterable

from ._graph import MISSING, FieldDef, TypeDef

_HASH_RE = re.compile(r"[0-9A-Za-z]{1,128}")
_NAME_RE = re.compile(r"[A-Za-z_][A-Za-z0-9_]*")
_TS_KEY_RE = re.compile(r"[A-Za-z_$][A-Za-z0-9_$]*")
_HEADER = "Generated by schema-codegen from a JSON Schema. DO NOT EDIT."

_PY_PRIMS = {
    "string": "str",
    "integer": "int",
    "number": "float",
    "boolean": "bool",
    "null": "None",
    "any": "Any",
    "object": "dict[str, Any]",
}
_TS_PRIMS = {
    "string": "string",
    "integer": "number",
    "number": "number",
    "boolean": "boolean",
    "null": "null",
    "any": "unknown",
    "object": "Record<string, unknown>",
}


def _check_hash(source_hash: str) -> None:
    if not _HASH_RE.fullmatch(source_hash):
        raise ValueError("source_hash must be 1-128 alphanumeric characters")


def _split(ref: str) -> list[str]:
    parts: list[str] = []
    cur: list[str] = []
    depth = 0
    for ch in ref:
        if ch == "<":
            depth += 1
        elif ch == ">":
            depth -= 1
        if ch == "|" and depth == 0:
            parts.append("".join(cur))
            cur = []
        else:
            cur.append(ch)
    parts.append("".join(cur))
    return parts


def _is_array(part: str) -> bool:
    return part.startswith("array<") and part.endswith(">")


def _py_type(ref: str) -> str:
    return " | ".join(_py_item(p) for p in _split(ref))


def _py_item(part: str) -> str:
    if _is_array(part):
        return f"list[{_py_type(part[6:-1])}]"
    return _PY_PRIMS.get(part, part)


def _ts_type(ref: str) -> str:
    return " | ".join(_ts_item(p) for p in _split(ref))


def _ts_item(part: str) -> str:
    if _is_array(part):
        inner = _ts_type(part[6:-1])
        return f"({inner})[]" if " | " in inner else f"{inner}[]"
    return _TS_PRIMS.get(part, part)


def _py_field(f: FieldDef) -> str:
    ann = _py_type(f.type_ref)
    if f.nullable:
        ann += " | None"
    has_default = f.default is not MISSING
    if (
        not f.required
        and not f.nullable
        and ann != "None"
        and (not has_default or f.default is None)
    ):
        ann += " | None"
    value: str | None
    if has_default:
        value = ascii(f.default)
    elif not f.required:
        value = "None"
    else:
        value = None
    extras: list[str] = []
    if f.py_name != f.name:
        extras.append(f"alias={f.name!a}")
    if f.description is not None:
        extras.append(f"description={f.description!a}")
    if extras:
        args = ([f"default={value}"] if value is not None else []) + extras
        joined = ", ".join(args)
        rhs = f" = Field({joined})"
    elif value is not None:
        rhs = f" = {value}"
    else:
        rhs = ""
    return f"    {f.py_name}: {ann}{rhs}"


def _py_class(d: TypeDef) -> str:
    body: list[str] = []
    if d.description is not None:
        body.append(f"    {d.description!a}")
    if d.closed:
        body.append("    model_config = ConfigDict(extra='forbid')")
    if d.fields and body:
        body.append("")
    body.extend(_py_field(f) for f in d.fields)
    if not body:
        body.append("    pass")
    return "\n".join([f"class {d.name}(BaseModel):", *body])


def _py_enum(d: TypeDef) -> str:
    literals = ", ".join(ascii(v) for v in d.values)
    return f"{d.name} = Literal[{literals}]"


def _py_alias(d: TypeDef) -> str:
    if d.kind == "union":
        return f"{d.name} = " + " | ".join(_py_type(m) for m in d.members)
    return f"{d.name} = {_py_type(d.target or 'any')}"


def _alias_order(defs: Iterable[TypeDef]) -> list[TypeDef]:
    items = {d.name: d for d in defs if d.kind in ("alias", "union")}

    def deps(name: str) -> list[str]:
        d = items[name]
        text = " ".join(d.members) if d.kind == "union" else (d.target or "")
        return sorted({r for r in _NAME_RE.findall(text) if r in items and r != name})

    order: list[TypeDef] = []
    seen: set[str] = set()
    for start in sorted(items):
        if start in seen:
            continue
        seen.add(start)
        stack = [(start, iter(deps(start)))]
        while stack:
            name, pending = stack[-1]
            for dep in pending:
                if dep not in seen:
                    seen.add(dep)
                    stack.append((dep, iter(deps(dep))))
                    break
            else:
                order.append(items[name])
                stack.pop()
    return order


def render_pydantic(defs: Iterable[TypeDef], *, source_hash: str) -> str:
    """Render Pydantic v2 models.

    Enums come first, then classes, then aliases and unions in dependency order, then one
    ``model_rebuild()`` call per class in name order.

    Raises:
        ValueError: if ``source_hash`` is not a short alphanumeric string.
    """
    _check_hash(source_hash)
    ordered = sorted(defs, key=lambda d: d.name)
    classes = [d for d in ordered if d.kind == "object"]
    prelude = (
        f"# {_HEADER}\n# Source schema SHA-256: {source_hash}\n\n"
        "from __future__ import annotations\n\n"
        "from typing import Any, Literal\n\n"
        "from pydantic import BaseModel, ConfigDict, Field"
    )
    parts = [prelude]
    parts.extend(_py_enum(d) for d in ordered if d.kind == "enum")
    parts.extend(_py_class(d) for d in classes)
    parts.extend(_py_alias(d) for d in _alias_order(ordered))
    if classes:
        parts.append("\n".join(f"{c.name}.model_rebuild()" for c in classes))
    return "\n\n\n".join(parts) + "\n"


def _ts_doc(text: str, indent: int) -> list[str]:
    safe = text.replace("*/", "*\\/")
    lines = safe.splitlines() or [""]
    pad = " " * indent
    if len(lines) == 1:
        return [f"{pad}/** {lines[0]} */"]
    return [f"{pad}/**", *[f"{pad} * {line}" for line in lines], f"{pad} */"]


def _ts_key(name: str) -> str:
    return name if _TS_KEY_RE.fullmatch(name) else json.dumps(name)


def _ts_block(d: TypeDef) -> str:
    lines: list[str] = []
    if d.description is not None:
        lines.extend(_ts_doc(d.description, 0))
    if d.kind == "object":
        if not d.fields:
            lines.append(f"export interface {d.name} {{}}")
            return "\n".join(lines)
        lines.append(f"export interface {d.name} {{")
        for f in d.fields:
            if f.description is not None:
                lines.extend(_ts_doc(f.description, 2))
            ts = _ts_type(f.type_ref) + (" | null" if f.nullable else "")
            mark = "" if f.required else "?"
            lines.append(f"  {_ts_key(f.name)}{mark}: {ts};")
        lines.append("}")
        return "\n".join(lines)
    if d.kind == "enum":
        rhs = " | ".join(json.dumps(v) for v in d.values)
    elif d.kind == "union":
        rhs = " | ".join(_ts_type(m) for m in d.members)
    else:
        rhs = _ts_type(d.target or "any")
    lines.append(f"export type {d.name} = {rhs};")
    return "\n".join(lines)


def render_typescript(defs: Iterable[TypeDef], *, source_hash: str) -> str:
    """Render TypeScript interfaces and type aliases.

    Raises:
        ValueError: if ``source_hash`` is not a short alphanumeric string.
    """
    _check_hash(source_hash)
    head = f"// {_HEADER}\n// Source schema SHA-256: {source_hash}"
    blocks = [_ts_block(d) for d in sorted(defs, key=lambda d: d.name)]
    return "\n\n".join([head, *blocks]) + "\n"
